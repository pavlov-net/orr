//! Generates each crate's private Windows bindings from `filters/<name>.txt` and the metadata in
//! windows-default. `tools/gen-windows-bindings.sh` runs it with the repository's root.

use std::path::Path;
use std::process::Command;
use std::{env, fs};

/// Raw bindings need only windows-link; typed ones need windows-core.
#[derive(Clone, Copy, PartialEq)]
enum Style {
    Raw,
    Typed,
}

/// Each set of bindings: its filter file's name, the file it goes in and its style.
const TARGETS: &[(&str, &str, Style)] = &[
    (
        "gpu_suite",
        "tests/gpu_suite/src/window/win32/bindings.rs",
        Style::Raw,
    ),
    (
        "orr_io",
        "crates/orr_io/src/windows/bindings.rs",
        Style::Raw,
    ),
    (
        "orr_window",
        "crates/orr_window/src/win32/bindings.rs",
        Style::Typed,
    ),
    (
        "orr_window_tests",
        "crates/orr_window/tests/display_watch/bindings.rs",
        Style::Raw,
    ),
    (
        "output_suite",
        "tests/output_suite/tests/watch_at_exit/bindings.rs",
        Style::Raw,
    ),
];

/// The I/O ring API, which windows-bindgen's newer metadata leaves out, so it comes from the
/// metadata of the older release pinned as windows-bindgen-ioring.
const IORING: &str = "crates/orr_io/src/windows/ioring.rs";

const HEADER: &str = "// Generated by tools/gen-windows-bindings.sh. Do not edit.
#![allow(
    non_upper_case_globals,
    non_camel_case_types,
    non_snake_case,
    dead_code,
    unreachable_pub,
    unused_qualifications,
    clippy::all,
    clippy::pedantic,
    clippy::restriction
)]
";

fn main() {
    let root = env::args_os().nth(1).expect("usage: windows-bindings ROOT");
    let root = Path::new(&root);
    for &(name, out, style) in TARGETS {
        let out = root.join(out);
        let mut bindgen = windows_bindgen::builder();
        bindgen.output(&out).flat().filter_file(filters(root, name));
        if style == Style::Raw {
            bindgen.sys();
        }
        bindgen.write();
        finish(&out, &fs::read_to_string(&out).unwrap());
    }
    ioring(root);
}

/// The file of `name`'s filters.
fn filters(root: &Path, name: &str) -> std::path::PathBuf {
    root.join(format!("tools/windows-bindings/filters/{name}.txt"))
}

/// Generates function types with no declarations to link against: older systems lack the API,
/// so a reference to one of its functions would stop a program loading there.
fn ioring(root: &Path) {
    let out = root.join(IORING);
    let names = fs::read_to_string(filters(root, "orr_io_ioring")).unwrap();
    let mut args = vec![
        "--in",
        "default",
        "--out",
        out.to_str().unwrap(),
        "--flat",
        "--sys",
        "--sys-fn-ptrs",
        "--no-allow",
        "--no-comment",
        "--filter",
    ];
    args.extend(names.split_whitespace());
    windows_bindgen_ioring::bindgen(args).unwrap();
    let text = fs::read_to_string(&out).unwrap();
    let text: String = text
        .lines()
        .filter(|line| !line.starts_with("windows_link::link!"))
        .map(|line| line.replace("windows_sys::core::HRESULT", "windows_result::HRESULT") + "\n")
        .collect();
    assert!(!text.contains("link!") && !text.contains("extern \"system\" {"));
    finish(&out, &text);
}

/// Writes `text` to `out` under the stamp and the lints generated code doesn't meet.
fn finish(out: &Path, text: &str) {
    fs::write(out, format!("{HEADER}{text}")).unwrap();
    let formatted = Command::new("rustfmt")
        .args(["--edition", "2024", "--config", "newline_style=Unix"])
        .arg(out)
        .status()
        .unwrap();
    assert!(formatted.success());
}
