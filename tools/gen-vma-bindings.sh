#!/usr/bin/env bash
# Regenerates crates/orr-memory/src/bindings.rs, the Rust bindings to Vulkan Memory
# Allocator's vma* API, from the header tools/fetch-slang.sh puts in .tools/vma (ORR_TOOLS,
# else the nearest .tools at or above the repository). Vulkan types are left out and come
# from ash instead, and the header is parsed for x86_64 Linux on every host, so the output
# depends on neither the host nor its Vulkan headers.
#
# Installs the pinned bindgen-cli into .tools on first use. Needs clang (CLANG, else clang on
# PATH, else the default LLVM install on Windows) and Vulkan 1.4 headers ($VULKAN_SDK/Include,
# else the system include path).
set -euo pipefail

bindgen_version=0.73.2

root="$(cd "$(dirname "$0")/.." && pwd)"
tools="${ORR_TOOLS:-}"
if [ -z "$tools" ]; then
  dir="$root"
  while [ ! -d "$dir/.tools" ] && [ "$dir" != "$(dirname "$dir")" ]; do
    dir="$(dirname "$dir")"
  done
  tools="$dir/.tools"
fi
out="$root/crates/orr-memory/src/bindings.rs"

vma_commit="$(sed -n 's/^vma_commit=//p' "$root/tools/fetch-slang.sh")"
if [ "$(git -C "$tools/vma" rev-parse HEAD 2>/dev/null)" != "$vma_commit" ]; then
  echo "$tools/vma is not VMA $vma_commit; run tools/fetch-slang.sh" >&2
  exit 1
fi
vma_version="$(sed -n 's/^#define VMA_VERSION (VK_MAKE_VERSION(\([0-9]*\), \([0-9]*\), \([0-9]*\)))/\1.\2.\3/p' \
  "$tools/vma/include/vk_mem_alloc.h")"

bindgen_root="$tools/bindgen-cli-$bindgen_version"
bindgen="$bindgen_root/bin/bindgen"
if [ ! -x "$bindgen" ] && [ ! -x "$bindgen.exe" ]; then
  cargo install --quiet --locked --root "$bindgen_root" bindgen-cli --version "$bindgen_version"
fi

clang="${CLANG:-clang}"
if ! command -v "$clang" > /dev/null && [ -x "/c/Program Files/LLVM/bin/clang.exe" ]; then
  clang="/c/Program Files/LLVM/bin/clang.exe"
fi
clang_args=(--target=x86_64-unknown-linux-gnu -ffreestanding
  -isystem "$("$clang" -print-resource-dir)/include" -I "$tools/vma/include")
if [ -n "${VULKAN_SDK:-}" ]; then
  clang_args+=(-I "$VULKAN_SDK/Include")
fi

"$bindgen" "$root/crates/orr-memory/src/vma.h" \
  --rust-target 1.97 \
  --rust-edition 2024 \
  --allowlist-function 'vma.*' \
  --allowlist-type 'Vma.*' \
  --blocklist-type 'Vk.*' \
  --blocklist-type 'PFN_vk.*' \
  --default-enum-style consts \
  --no-prepend-enum-name \
  --with-derive-default \
  --no-layout-tests \
  --no-doc-comments \
  --formatter prettyplease \
  --raw-line "// Generated by tools/gen-vma-bindings.sh from VulkanMemoryAllocator v$vma_version ($vma_commit). Do not edit." \
  -o "$out.tmp" \
  -- "${clang_args[@]}"
tr -d '\r' < "$out.tmp" > "$out"
rm "$out.tmp"
echo "bindings in $out"
