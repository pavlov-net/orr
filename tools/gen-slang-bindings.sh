#!/usr/bin/env bash
# Regenerates crates/orr_shaders/src/build/slang_sys.rs, the Rust bindings to the Slang API,
# from the release tools/fetch-slang.sh puts in .tools (ORR_TOOLS, else the nearest .tools at
# or above the repository).
#
# The committed file is generated on Windows x64 and works on every platform, and this script
# runs only on Windows: slang.h parsed elsewhere gives the same API, but some enums wrap c_uint
# instead of c_int. spReflection_GetSession is left out because its exported name differs by
# platform and the generated loader needs every symbol to load the library.
#
# Installs the pinned bindgen-cli into .tools on first use. Needs libclang (LIBCLANG_PATH, else
# the default LLVM install).
set -euo pipefail

case "$(uname -s)" in
  MINGW* | MSYS* | CYGWIN*) ;;
  *)
    echo "run this on Windows: the committed bindings are generated there" >&2
    exit 1
    ;;
esac

bindgen_version=0.73.2

root="$(cd "$(dirname "$0")/.." && pwd)"
tools="${ORR_TOOLS:-}"
if [ -z "$tools" ]; then
  dir="$root"
  while [ ! -d "$dir/.tools" ] && [ "$dir" != "$(dirname "$dir")" ]; do
    dir="$(dirname "$dir")"
  done
  tools="$dir/.tools"
fi
out="$root/crates/orr_shaders/src/build/slang_sys.rs"

slang_version="$(sed -n 's/^slang_version=//p' "$root/tools/fetch-slang.sh")"
include="$tools/slang-$slang_version/include"
if ! grep -q "SLANG_TAG_VERSION \"$slang_version\"" "$include/slang-tag-version.h" 2>/dev/null; then
  echo "$tools/slang-$slang_version is not Slang $slang_version; run tools/fetch-slang.sh" >&2
  exit 1
fi

bindgen_root="$tools/bindgen-cli-$bindgen_version"
bindgen="$bindgen_root/bin/bindgen"
if [ ! -x "$bindgen" ] && [ ! -x "$bindgen.exe" ]; then
  cargo install --quiet --locked --root "$bindgen_root" bindgen-cli --version "$bindgen_version"
fi

"$bindgen" "$include/slang.h" \
  --rust-target 1.97 \
  --rust-edition 2024 \
  --allowlist-type 'slang::.*' \
  --allowlist-type 'Slang.*' \
  --allowlist-function 'spReflection.*' \
  --allowlist-function spGetBuildTagString \
  --allowlist-function slang_createGlobalSession2 \
  --blocklist-function spReflection_GetSession \
  --allowlist-var 'SLANG_TARGET_FLAG_.*' \
  --generate functions,types,vars \
  --vtable-generation \
  --wrap-unsafe-ops \
  --no-layout-tests \
  --no-doc-comments \
  --with-derive-default \
  --default-enum-style newtype \
  --dynamic-loading SlangLib \
  --dynamic-link-require-all \
  --formatter prettyplease \
  --raw-line "// Generated by tools/gen-slang-bindings.sh from Slang $slang_version on Windows x64 (Apache-2.0 WITH LLVM-exception). Do not edit." \
  -o "$out.tmp" \
  -- -xc++ -std=c++17
tr -d '\r' < "$out.tmp" > "$out"
rm "$out.tmp"
echo "bindings in $out"
