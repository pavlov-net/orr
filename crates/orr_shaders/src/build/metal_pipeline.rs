//! The Metal form of a module's ray tracing entries, after `orr_shaders.pipeline`'s compute form.
//!
//! [`generate`] writes Slang appended to the module in the Metal session: a launch kernel per
//! raygen, and per other stage a body that calls the entry with what it takes, with a kernel that
//! calls every body so Slang emits them. Slang cannot emit the rest, so [`wrap`] appends it to the
//! stage program's MSL: per closest-hit, miss and callable a `[[visible]]` function, per any-hit a
//! triangle intersection function, and per intersection, alone and with each procedural any-hit
//! of the module, a bounding-box intersection function. Each builds the context Slang's functions
//! take (`KernelContext`) and calls its body. [`wrap`] fails when Slang's MSL is not of the shape
//! the wrappers expect.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use super::model::{Entry, Model, ParamRole};
use crate::Stage;

/// The Slang name of a triangle hit's attributes in the module's SPIR-V; the compute form's
/// `TriangleAttributes` is the hit itself.
const TRIANGLE_ATTRIBUTES: &str = "BuiltInTriangleIntersectionAttributes";

/// The intersection tags of every intersector and intersection function, as
/// `orr_shaders.pipeline`'s prelude has them.
const TAGS: &str =
    "triangle_data, instancing, world_space_data, max_levels<3>, intersection_function_buffer";

/// The Slang kernel that keeps the stage bodies.
pub(super) const KEEP_KERNEL: &str = "orr_keep_stages";

/// The launch kernel of raygen `entry`.
pub(super) fn launch_kernel(entry: &str) -> String {
    format!("orr_launch_{entry}")
}

fn body(entry: &str) -> String {
    format!("orr_body_{entry}")
}

/// What [`generate`] made of a module.
pub(super) struct Generated {
    /// Slang to append to the module.
    pub(super) slang: String,
    /// Whether it has stage bodies, which [`KEEP_KERNEL`] keeps.
    pub(super) stages: bool,
}

/// The arguments an entry is called with in its body, where the body's parameters are
/// `orr_stage_data`, `orr_stage_hit` and `orr_stage_record`.
fn arguments(e: &Entry) -> Result<String, String> {
    let mut args = Vec::new();
    for p in &e.params {
        args.push(match p.role {
            ParamRole::Data => "orr_stage_data".to_owned(),
            ParamRole::Attributes if p.ty == TRIANGLE_ATTRIBUTES => {
                "triangle_attributes(orr_stage_hit)".to_owned()
            }
            ParamRole::Attributes => format!("orr_stage_hit.attributes<{}>()", p.ty),
            ParamRole::Record(offset) => {
                format!("*({}*)(orr_stage_record + 32 + {offset})", p.ty)
            }
        });
    }
    let data = e
        .params
        .iter()
        .filter(|p| p.role == ParamRole::Data)
        .count();
    let attributes = e
        .params
        .iter()
        .filter(|p| p.role == ParamRole::Attributes)
        .count();
    let want = match e.stage {
        Stage::RayGen | Stage::Intersection => (0, 0),
        Stage::ClosestHit | Stage::AnyHit => (1, 1),
        Stage::Miss | Stage::Callable => (1, 0),
        _ => unreachable!("not a ray tracing stage"),
    };
    // A hit shader may leave out its attributes.
    let ok = data == want.0 && (attributes == want.1 || want.1 == 1 && attributes == 0);
    if !ok {
        return Err(format!(
            "{:?} entry {} has {data} payload and {attributes} attribute parameters",
            e.stage, e.name
        ));
    }
    Ok(args.join(", "))
}

/// The payload or callable data type of a stage entry.
fn data_type(e: &Entry) -> Option<&str> {
    e.params
        .iter()
        .find(|p| p.role == ParamRole::Data)
        .map(|p| p.ty.as_str())
}

/// The record address of a raygen's record data, which its launch kernel reads.
const RAYGEN_RECORD: &str = "pipeline_raygen_record()";

/// The Slang the Metal session appends to a module with ray tracing entries; `None` without any.
pub(super) fn generate(model: &Model) -> Result<Option<Generated>, String> {
    let rt: Vec<&Entry> = model
        .entries
        .iter()
        .filter(|e| e.stage.ray_tracing())
        .collect();
    if rt.is_empty() {
        return Ok(None);
    }
    let mut s = String::from("\n// Generated by orr_shaders::build for the Metal session.\n");
    let mut keep = String::new();
    for e in &rt {
        let args = arguments(e)?;
        match e.stage {
            Stage::RayGen => {
                let args = args.replace("orr_stage_record", RAYGEN_RECORD);
                writeln!(
                    s,
                    "[shader(\"compute\")]\n[numthreads(64, 1, 1)]\nvoid {}(uint3 id : SV_DispatchThreadID, uint lane : SV_GroupIndex)\n{{\n    pipeline_launch(id, lane);\n    {}({args});\n}}",
                    launch_kernel(&e.name),
                    e.name
                )
                .unwrap();
            }
            Stage::ClosestHit | Stage::Miss | Stage::Callable => {
                let data = data_type(e).expect("checked by arguments");
                writeln!(
                    s,
                    "void {}(inout {data} orr_stage_data, Traced orr_stage_hit, uint64_t orr_stage_record)\n{{\n    {}({args});\n}}",
                    body(&e.name),
                    e.name
                )
                .unwrap();
                writeln!(
                    keep,
                    "    {{\n        {data} d = *({data}*)at;\n        {}(d, h, at);\n        *({data}*)at = d;\n    }}",
                    body(&e.name)
                )
                .unwrap();
            }
            Stage::AnyHit => {
                let data = data_type(e).expect("checked by arguments");
                writeln!(
                    s,
                    "uint2 {}(inout {data} orr_stage_data, Traced orr_stage_hit, uint64_t orr_stage_record)\n{{\n    any_hit_begin();\n    {}({args});\n    return any_hit_result();\n}}",
                    body(&e.name),
                    e.name
                )
                .unwrap();
                writeln!(
                    keep,
                    "    {{\n        {data} d = *({data}*)at;\n        *(uint2*)at = {}(d, h, at);\n        *({data}*)at = d;\n    }}",
                    body(&e.name)
                )
                .unwrap();
            }
            Stage::Intersection => {
                writeln!(
                    s,
                    "uint4 {}(Traced orr_stage_hit, uint64_t orr_stage_record)\n{{\n    intersection_begin();\n    {}({args});\n    return intersection_report();\n}}",
                    body(&e.name),
                    e.name
                )
                .unwrap();
                writeln!(keep, "    *(uint4*)at = {}(h, at);", body(&e.name)).unwrap();
            }
            _ => unreachable!("a ray tracing stage"),
        }
    }
    let stages = !keep.is_empty();
    if stages {
        writeln!(
            s,
            "[shader(\"compute\")]\n[numthreads(1, 1, 1)]\nvoid {KEEP_KERNEL}(uint3 id : SV_DispatchThreadID)\n{{\n    pipeline_prelude();\n    Traced h = traced_nothing();\n    uint64_t at = pipeline_raygen_record();\n{keep}}}"
        )
        .unwrap();
    }
    Ok(Some(Generated { slang: s, stages }))
}

/// A function's MSL signature: name, return type and parameter types.
struct Signature {
    name: String,
    ret: String,
    params: Vec<String>,
}

/// The signature of the first function of `msl` named `name` or `name_N`.
fn find_function(msl: &str, name: &str) -> Option<Signature> {
    // Definitions start their line; comments and calls do not count.
    for line in msl
        .lines()
        .filter(|l| l.starts_with(|c: char| c.is_ascii_alphabetic()))
    {
        let Some(open) = line.find('(') else {
            continue;
        };
        let head = &line[..open];
        let mut words = head.rsplitn(2, ' ');
        let (Some(fname), Some(ret)) = (words.next(), words.next()) else {
            continue;
        };
        let renamed = fname
            .strip_prefix(name)
            .and_then(|rest| rest.strip_prefix('_'))
            .is_some_and(|n| !n.is_empty() && n.bytes().all(|b| b.is_ascii_digit()));
        if (fname != name && !renamed) || ret.starts_with(' ') || ret.contains('=') {
            continue;
        }
        let close = line.rfind(')')?;
        let params = split_params(&line[open + 1..close])
            .into_iter()
            .map(|p| {
                let p = p.trim();
                // Drop the parameter's name.
                p[..p.rfind(' ').unwrap_or(p.len())].trim().to_owned()
            })
            .filter(|p| !p.is_empty())
            .collect();
        return Some(Signature {
            name: fname.to_owned(),
            ret: ret.trim().to_owned(),
            params,
        });
    }
    None
}

fn split_params(list: &str) -> Vec<&str> {
    let mut out = Vec::new();
    let (mut depth, mut start) = (0i32, 0);
    for (i, c) in list.char_indices() {
        match c {
            '<' | '(' | '[' => depth += 1,
            '>' | ')' | ']' => depth -= 1,
            ',' if depth == 0 => {
                out.push(&list[start..i]);
                start = i + 1;
            }
            _ => {}
        }
    }
    if !list[start..].trim().is_empty() {
        out.push(&list[start..]);
    }
    out
}

/// The fields of `struct KernelContext_0`: type and name.
fn kernel_context(msl: &str) -> Option<Vec<(String, String)>> {
    const HEAD: &str = "struct KernelContext_0\n{\n";
    let start = msl.find(HEAD)?;
    let body = &msl[start + HEAD.len()..];
    let end = body.find("\n};")?;
    Some(
        body[..end]
            .lines()
            .filter_map(|l| {
                let l = l.trim().strip_suffix(';')?;
                let at = l.rfind(' ')?;
                Some((l[..at].trim().to_owned(), l[at + 1..].to_owned()))
            })
            .collect(),
    )
}

/// `name` without Slang's `_N` suffix.
fn base_name(name: &str) -> &str {
    match name.rsplit_once('_') {
        Some((base, n)) if !n.is_empty() && n.bytes().all(|b| b.is_ascii_digit()) => base,
        _ => name,
    }
}

/// Where a wrapper finds what its context's fields take.
struct Sources<'a> {
    root: &'a str,
    pool: &'a str,
    samplers: &'a str,
    launch: &'a str,
    index: &'a str,
    hit: &'a str,
    t_min: &'a str,
}

/// The statements that build the context `ctx` from `sources`, or the field no wrapper can fill.
fn context(fields: &[(String, String)], sources: &Sources<'_>) -> Result<String, String> {
    let mut s = String::from("    thread KernelContext_0 ctx;\n");
    for (ty, name) in fields {
        let value = match base_name(name) {
            "root" | "metal_root" | "metal_launch" | "metal_samplers" => {
                let from = match base_name(name) {
                    "root" | "metal_root" => sources.root,
                    "metal_launch" => sources.launch,
                    _ => sources.samplers,
                };
                format!("({ty})({from})")
            }
            "metal_texture_pool" => sources.pool.to_owned(),
            "orr_index" => sources.index.to_owned(),
            "orr_hit" => sources.hit.to_owned(),
            "orr_t_min" => sources.t_min.to_owned(),
            "orr_decision" => "0".to_owned(),
            "orr_report" => "uint4(0)".to_owned(),
            other => {
                return Err(format!(
                    "the stage program's context has a field `{ty} {other}` that no wrapper fills: a stage reads a global or static the compute form does not hand it"
                ));
            }
        };
        writeln!(s, "    ctx.{name} = {value};").unwrap();
    }
    Ok(s)
}

/// A stage body as Slang emitted it.
struct Body {
    name: String,
    /// The MSL type of its payload or callable data; none for an intersection's.
    data: Option<String>,
    /// It takes the context.
    context: bool,
}

/// The body of `entry` in `msl`, checked against its stage's shape.
fn emitted_body(msl: &str, e: &Entry, traced: &str) -> Result<Body, String> {
    let name = body(&e.name);
    let sig =
        find_function(msl, &name).ok_or_else(|| format!("Slang's MSL has no function {name}"))?;
    let fname = sig.name.clone();
    let (ret, lead) = match e.stage {
        Stage::Intersection => ("uint4", 0),
        Stage::AnyHit => ("uint2", 1),
        _ => ("void", 1),
    };
    let hit = format!("const {traced} thread*");
    let p = &sig.params;
    let shape = sig.ret == ret
        && (p.len() == lead + 2 || p.len() == lead + 3 && p[lead + 2] == "KernelContext_0 thread*")
        && p[lead] == hit
        && p[lead + 1] == "ulong"
        && (lead == 0 || p[0].ends_with(" thread*"));
    if !shape {
        return Err(format!(
            "Slang's MSL declares {fname} as `{} ({})`, not the shape the wrappers call",
            sig.ret,
            p.join(", ")
        ));
    }
    Ok(Body {
        name: fname,
        data: (lead == 1).then(|| p[0].trim_end_matches(" thread*").to_owned()),
        context: p.len() == lead + 3,
    })
}

/// `msl`, the stage program of a module, with its wrappers appended, and each stage entry's
/// function name: `[[visible]]` closest-hit, miss and callable functions `orr_stage_<symbol>`,
/// any-hit triangle intersection functions `orr_anyhit_<symbol>`, and intersection bounding-box
/// functions `orr_isect_<symbol>`, with a function `orr_isect_<symbol>__<any-hit>` for each
/// procedural any-hit of the module, which runs it on the report. `symbol` names an entry's
/// functions after its module.
pub(super) fn wrap(
    msl: &str,
    model: &Model,
    symbol: impl Fn(&str) -> String,
) -> Result<(String, BTreeMap<String, String>), String> {
    let fields = kernel_context(msl).unwrap_or_default();
    let traced = find_function(msl, "traced_nothing")
        .map(|s| s.ret)
        .filter(|t| t.starts_with("Traced"))
        .ok_or("Slang's MSL has no `Traced traced_nothing()`, which names the hit type")?;
    let mut out = String::from(msl);
    out.push_str("\n// Wrappers generated by orr_shaders::build.\n");
    let mut names = BTreeMap::new();
    let stages: Vec<&Entry> = model
        .entries
        .iter()
        .filter(|e| e.stage.ray_tracing() && e.stage != Stage::RayGen)
        .collect();
    let mut bodies = BTreeMap::new();
    for e in &stages {
        bodies.insert(e.name.as_str(), emitted_body(msl, e, &traced)?);
    }
    let call = |b: &Body, args: &str| {
        if b.context {
            format!("{}({args}, &ctx)", b.name)
        } else {
            format!("{}({args})", b.name)
        }
    };
    let visible = Sources {
        root: "root",
        pool: "pool",
        samplers: "samplers",
        launch: "launch",
        index: "index",
        hit: &format!("*(thread const {traced}*)hit"),
        t_min: "0.0f",
    };
    let ray_data = Sources {
        root: "rd.root",
        pool: "rd.pool",
        samplers: "rd.samplers",
        launch: "rd.launch",
        index: "uint3(rd.index_x, rd.index_y, rd.index_z)",
        hit: "hit",
        t_min: "t_min",
    };
    // A procedural group without an any-hit declares the payload of the module's other stages.
    let mut payloads: Vec<&str> = bodies
        .iter()
        .filter(|(n, _)| {
            stages
                .iter()
                .any(|e| e.name == **n && matches!(e.stage, Stage::ClosestHit | Stage::AnyHit))
        })
        .filter_map(|(_, b)| b.data.as_deref())
        .collect();
    payloads.sort_unstable();
    payloads.dedup();
    for e in &stages {
        let b = &bodies[e.name.as_str()];
        match e.stage {
            Stage::ClosestHit | Stage::Miss | Stage::Callable => {
                let name = format!("orr_stage_{}", symbol(&e.name));
                let data = b.data.as_deref().expect("a stage takes data");
                write!(
                    out,
                    "[[visible]] void {name}(thread void* data, thread const void* hit, ulong record, uint3 index, constant void* root, constant ulong* pool, device void* samplers, constant void* launch)\n{{\n{}    {};\n}}\n",
                    context(&fields, &visible)?,
                    call(b, &format!("(thread {data}*)data, (thread const {traced}*)hit, record"))
                )
                .unwrap();
                names.insert(e.name.clone(), name);
            }
            Stage::AnyHit => {
                let name = format!("orr_anyhit_{}", symbol(&e.name));
                let data = b.data.as_deref().expect("an any-hit takes data");
                write!(
                    out,
                    "[[intersection(triangle, {TAGS})]]\norr_any_result {name}(float distance [[distance]], float2 bary [[barycentric_coord]], bool front [[front_facing]], array_ref<uint> instance [[instance_id]], array_ref<uint> user [[user_instance_id]], const device void* data [[primitive_data]], float3 origin [[world_space_origin]], float3 direction [[world_space_direction]], float t_min [[min_distance]], uint function_id [[function_id]], ray_data orr_ray_data<{data}>& rd [[payload]])\n{{\n    ulong at = reinterpret_cast<ulong>(data);\n    {traced} hit = {{uint4(function_id, as_type<uint>(distance), instance[0], (user[0] & 0xffffffu) | ((front ? 0xfeu : 0xffu) << 24)), uint4(uint(at), uint(at >> 32), as_type<uint2>(bary)), uint4(as_type<uint3>(origin), as_type<uint>(direction.x)), uint4(as_type<uint2>(direction.yz), uint(rd.tlas), uint(rd.tlas >> 32))}};\n{}    {data} p = rd.payload;\n    uint2 d = {};\n    rd.payload = p;\n    return {{d.x != 0, d.y != 0}};\n}}\n",
                    context(&fields, &ray_data)?,
                    call(b, "&p, &hit, rd.hits + ulong(function_id) * rd.hit_stride")
                )
                .unwrap();
                names.insert(e.name.clone(), name);
            }
            Stage::Intersection => {
                let name = format!("orr_isect_{}", symbol(&e.name));
                let procedural: Vec<&&Entry> = stages
                    .iter()
                    .filter(|h| {
                        h.stage == Stage::AnyHit
                            && h.params.iter().any(|p| {
                                p.role == ParamRole::Attributes && p.ty != TRIANGLE_ATTRIBUTES
                            })
                    })
                    .collect();
                let alone = match payloads.as_slice() {
                    [one] => Some(*one),
                    _ => None,
                };
                for any in std::iter::once(None).chain(procedural.into_iter().map(Some)) {
                    let (fname, data) = match any {
                        Some(h) => (
                            format!("{name}__{}", h.name),
                            bodies[h.name.as_str()]
                                .data
                                .clone()
                                .expect("an any-hit takes data"),
                        ),
                        None => match alone {
                            Some(d) => (name.clone(), d.to_owned()),
                            None => {
                                return Err(format!(
                                    "intersection {} serves groups without an any-hit, whose payload is the module's other stages': they take {} payload types",
                                    e.name,
                                    payloads.len()
                                ));
                            }
                        },
                    };
                    let mut any_hit = String::new();
                    if let Some(h) = any {
                        let hb = &bodies[h.name.as_str()];
                        let field = fields
                            .iter()
                            .find(|(_, n)| base_name(n) == "orr_hit")
                            .map_or_default(|(_, n)| format!("    ctx.{n} = hit;\n"));
                        write!(
                            any_hit,
                            "{field}    {data} p = rd.payload;\n    uint2 d = {};\n    rd.payload = p;\n    if (d.x == 0)\n        return {{false, true, 0.0f}};\n",
                            call(hb, "&p, &hit, record")
                        )
                        .unwrap();
                    }
                    let more = if any.is_some() { "d.y != 0" } else { "true" };
                    write!(
                        out,
                        "[[intersection(bounding_box, {TAGS})]]\norr_box_result {fname}(uint geometry [[geometry_id]], uint primitive [[primitive_id]], array_ref<uint> instance [[instance_id]], array_ref<uint> user [[user_instance_id]], float3 origin [[world_space_origin]], float3 direction [[world_space_direction]], float t_min [[min_distance]], float t_max [[max_distance]], uint function_id [[function_id]], ray_data orr_ray_data<{data}>& rd [[payload]])\n{{\n    ulong record = rd.hits + ulong(function_id) * rd.hit_stride;\n    uint4 w2 = uint4(as_type<uint3>(origin), as_type<uint>(direction.x));\n    uint4 w3 = uint4(as_type<uint2>(direction.yz), uint(rd.tlas), uint(rd.tlas >> 32));\n    {traced} hit = {{uint4(function_id, as_type<uint>(t_max), instance[0], user[0] & 0xffffffu), uint4(geometry, primitive, 0, 0), w2, w3}};\n{}    uint4 r = {};\n    if (r.x == 0)\n        return {{false, true, 0.0f}};\n    float t = as_type<float>(r.y);\n    if (!(t >= t_min && t <= t_max))\n        return {{false, true, 0.0f}};\n    hit = {{uint4(function_id, r.y, instance[0], (user[0] & 0xffffffu) | ((r.x >> 1) << 24)), uint4(geometry, primitive, r.z, r.w), w2, w3}};\n{any_hit}    rd.kind = r.x >> 1;\n    rd.attribute_x = r.z;\n    rd.attribute_y = r.w;\n    return {{true, {more}, t}};\n}}\n",
                        context(&fields, &ray_data)?,
                        call(b, "&hit, record")
                    )
                    .unwrap();
                }
                names.insert(e.name.clone(), name);
            }
            _ => unreachable!("a stage"),
        }
    }
    Ok((out, names))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn signatures_and_contexts_parse() {
        let msl = "\
struct KernelContext_0
{
    Root_0 constant* root_0;
    array<uint, int(3)> threadgroup* orr_any_0;
    uint3 orr_index_0;
};
// orr_body_a_0(x)
uint2 orr_body_a_0(Payload_0 thread* data_1, const Traced_0 thread* hit_1, ulong record_1, KernelContext_0 thread* kernelContext_8)
{
";
        let s = find_function(msl, "orr_body_a").unwrap();
        assert_eq!(s.ret, "uint2");
        assert_eq!(
            s.params,
            [
                "Payload_0 thread*",
                "const Traced_0 thread*",
                "ulong",
                "KernelContext_0 thread*"
            ]
        );
        assert!(find_function(msl, "orr_body").is_none());
        let fields = kernel_context(msl).unwrap();
        assert_eq!(fields[1].0, "array<uint, int(3)> threadgroup*");
        assert_eq!(base_name(&fields[2].1), "orr_index");
    }
}
