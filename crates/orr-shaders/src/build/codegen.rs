//! Rust source for a crate's compiled kernels.

use std::collections::{BTreeMap, HashMap};
use std::fmt::Write;
use std::path::Path;

use super::layout::{Plan, Slot};
use super::link::LinkPoint;
use super::model::{Model, Scalar, SpecConstant, StructDef, Ty};

/// Where a struct's Rust type lives.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) enum Owner {
    /// The crate's `types` module.
    Types,
    /// The module of the kernel whose file declares it.
    Kernel,
    /// A hand-written type named by `Build::extern_type`.
    Extern(String),
}

/// One kernel module, ready to emit.
pub(crate) struct Kernel<'a> {
    pub(crate) name: &'a str,
    pub(crate) spv: &'a Path,
    pub(crate) omm: Option<&'a Path>,
    pub(crate) hash: u64,
    /// Shared by every entry point: they share the root and the constants.
    pub(crate) interface: u64,
    pub(crate) model: &'a Model,
    pub(crate) owners: &'a HashMap<String, Owner>,
    pub(crate) plans: &'a HashMap<String, Plan>,
}

/// The crate's `types` module contents and its extern checks.
pub(crate) struct Shared<'a> {
    pub(crate) types: BTreeMap<String, (&'a StructDef, &'a Plan)>,
    pub(crate) externs: BTreeMap<String, (&'a StructDef, &'a Plan, String)>,
}

const ALLOW: &str = "#[allow(dead_code, non_camel_case_types, non_snake_case, unreachable_pub, unused_qualifications, clippy::all, clippy::pedantic)]";

pub(crate) fn generate(kernels: &[Kernel<'_>], shared: &Shared<'_>, manifest: &Path) -> String {
    let mut out = String::from("// Generated by orr_shaders::build. Do not edit.\n\n");
    let externs: HashMap<String, Owner> = shared
        .externs
        .iter()
        .map(|(name, (.., path))| (name.clone(), Owner::Extern(path.clone())))
        .collect();
    let _ = writeln!(out, "{ALLOW}\npub mod types {{");
    for (def, plan) in shared.types.values() {
        emit_struct(&mut out, def, plan, &|ty| rust_type(ty, 1, None, &externs));
    }
    out.push_str("}\n\n");
    if !shared.externs.is_empty() {
        let _ = writeln!(out, "{ALLOW}\nconst _: () = {{");
        for (def, plan, path) in shared.externs.values() {
            emit_asserts(&mut out, path, def, plan);
        }
        out.push_str("};\n");
        let _ = writeln!(
            out,
            "{ALLOW}\nconst _: fn() = || {{\n    fn pod<T: ::orr_shaders::bytemuck::Pod>() {{}}"
        );
        for (.., path) in shared.externs.values() {
            let _ = writeln!(out, "    pod::<{path}>();");
        }
        out.push_str("};\n\n");
    }

    // Kernels nest by path: "a/b" is `pub mod a { pub mod b { .. } }`.
    let mut tree = Tree::default();
    for k in kernels {
        let mut node = &mut tree;
        for part in k.name.split('/') {
            node = node.children.entry(ident(part)).or_default();
        }
        node.kernel = Some(k);
    }
    for (name, child) in &tree.children {
        let _ = writeln!(out, "{ALLOW}");
        emit_tree(&mut out, name, child, 1, manifest);
    }
    out
}

/// `orr_kernels.rs`: `KERNELS` over the linked modules and the id constants of the
/// switch points. Linked modules generate no Rust types; their roots are the renderer's.
pub(crate) fn kernel_set(
    kernels: &[Kernel<'_>],
    ids: &BTreeMap<LinkPoint, Vec<(&str, u8)>>,
    manifest: &Path,
) -> String {
    let mut out = String::from("// Generated by orr_shaders::build. Do not edit.\n\n");
    out.push_str(
        "/// The kernels compiled with this build's linked types.\npub static KERNELS: ::orr_shaders::KernelSet = ::orr_shaders::KernelSet {\n    modules: &[",
    );
    for i in 0..kernels.len() {
        let _ = write!(out, "&MODULE_{i}, ");
    }
    out.push_str("],\n};\n");
    for (point, list) in ids {
        let _ = writeln!(
            out,
            "\n/// {point:?} ids in link order; 0 is the default type.\n{ALLOW}\npub mod {} {{",
            point.label()
        );
        for (name, id) in list {
            let _ = writeln!(out, "    pub const {}: u8 = {id};", name.to_uppercase());
        }
        out.push_str("}\n");
    }
    for (i, k) in kernels.iter().enumerate() {
        out.push('\n');
        emit_module(&mut out, &format!("static MODULE_{i}"), k, manifest);
    }
    out
}

#[derive(Default)]
struct Tree<'a, 'b> {
    kernel: Option<&'b Kernel<'a>>,
    children: BTreeMap<String, Tree<'a, 'b>>,
}

fn emit_tree(out: &mut String, name: &str, node: &Tree<'_, '_>, depth: usize, manifest: &Path) {
    let _ = writeln!(out, "pub mod {name} {{");
    if let Some(k) = node.kernel {
        emit_kernel(out, k, depth, manifest);
    }
    for (child_name, child) in &node.children {
        emit_tree(out, child_name, child, depth + 1, manifest);
    }
    out.push_str("}\n");
}

fn emit_kernel(out: &mut String, k: &Kernel<'_>, depth: usize, manifest: &Path) {
    let ty = |t: &Ty| rust_type(t, depth, Some(k.name), k.owners);
    emit_module(out, "pub static MODULE", k, manifest);

    if let Some(root) = &k.model.root {
        let local = k.owners.get(root) == Some(&Owner::Kernel);
        if !(local && rust_name(root) == "Root") {
            let _ = writeln!(out, "pub type Root = {};", ty(&Ty::Struct(root.clone())));
        }
    }
    emit_spec(out, &k.model.spec);

    for (name, def) in &k.model.structs {
        if k.owners.get(name) == Some(&Owner::Kernel) {
            emit_struct(out, def, &k.plans[name], &ty);
        }
    }
}

/// The `ShaderModule` static of one kernel, declared as `item`.
fn emit_module(out: &mut String, item: &str, k: &Kernel<'_>, manifest: &Path) {
    let omm = match k.omm {
        Some(p) => format!(
            "::orr_shaders::aligned_spirv!({:?})",
            p.display().to_string()
        ),
        None => "&[]".to_owned(),
    };
    let _ = writeln!(
        out,
        "{item}: ::orr_shaders::ShaderModule = ::orr_shaders::ShaderModule {{\n    name: {name:?},\n    kernel: {name:?},\n    spirv: ::orr_shaders::aligned_spirv!({spv:?}),\n    spirv_omm: {omm},\n    hash: {hash:#018x},\n    manifest: {manifest:?},\n    entry_points: &[",
        name = k.name,
        spv = k.spv.display().to_string(),
        hash = k.hash,
        manifest = manifest.display().to_string(),
    );
    for e in &k.model.entries {
        let _ = writeln!(
            out,
            "        ::orr_shaders::EntryPoint {{ name: c{:?}, stage: ::orr_shaders::Stage::{:?}, workgroup: {:?}, interface: {:#018x} }},",
            e.name, e.stage, e.workgroup, k.interface
        );
    }
    out.push_str("    ],\n};\n");
}

fn emit_spec(out: &mut String, spec: &[SpecConstant]) {
    let mut offset = 0u32;
    let mut entries = Vec::new();
    for s in spec {
        let size = s.scalar.size();
        offset = offset.next_multiple_of(size);
        entries.push((s, offset, size));
        offset += size;
    }
    let total = offset;
    if spec.is_empty() {
        out.push_str(
            "/// Specialisation constants: none.\n#[derive(Clone, Copy, Debug, Default, PartialEq)]\npub struct Spec;\n\nimpl Spec {\n    pub const ENTRIES: &'static [::orr_shaders::abi::SpecEntry] = &[];\n\n    pub fn bytes(&self) -> [u8; 0] {\n        []\n    }\n}\n",
        );
        return;
    }
    out.push_str("/// Specialisation constants.\n#[derive(Clone, Copy, Debug, PartialEq)]\npub struct Spec {\n");
    for s in spec {
        let _ = writeln!(
            out,
            "    pub {}: {},",
            field_ident(&snake(&s.name)),
            spec_type(s.scalar)
        );
    }
    out.push_str("}\n\nimpl Default for Spec {\n    fn default() -> Self {\n        Self {\n");
    for s in spec {
        let _ = writeln!(
            out,
            "            {}: {},",
            field_ident(&snake(&s.name)),
            spec_value(s)
        );
    }
    out.push_str("        }\n    }\n}\n\nimpl Spec {\n    pub const ENTRIES: &'static [::orr_shaders::abi::SpecEntry] = &[\n");
    for (s, offset, size) in &entries {
        let _ = writeln!(
            out,
            "        ::orr_shaders::abi::SpecEntry {{ constant_id: {}, offset: {offset}, size: {size} }},",
            s.id
        );
    }
    let _ = writeln!(
        out,
        "    ];\n\n    /// The values as `ENTRIES` lays them out; booleans as 32-bit `VkBool32`.\n    pub fn bytes(&self) -> [u8; {total}] {{\n        let mut b = [0u8; {total}];"
    );
    for (s, offset, size) in &entries {
        let field = field_ident(&snake(&s.name));
        let value = if s.scalar == Scalar::Bool {
            format!("u32::from(self.{field})")
        } else {
            format!("self.{field}")
        };
        let _ = writeln!(
            out,
            "        b[{offset}..{}].copy_from_slice(&{value}.to_le_bytes());",
            offset + size
        );
    }
    out.push_str("        b\n    }\n}\n");
}

fn spec_type(s: Scalar) -> &'static str {
    if s == Scalar::Bool { "bool" } else { s.rust() }
}

fn spec_value(s: &SpecConstant) -> String {
    let b = s.default;
    match s.scalar {
        Scalar::Bool => (b != 0).to_string(),
        Scalar::F32 => format!("f32::from_bits({:#x})", b as u32),
        Scalar::F64 => format!("f64::from_bits({b:#x})"),
        Scalar::I8 => (b as u8 as i8).to_string(),
        Scalar::I16 => (b as u16 as i16).to_string(),
        Scalar::I32 => (b as u32 as i32).to_string(),
        Scalar::I64 => (b as i64).to_string(),
        Scalar::U8 => (b as u8).to_string(),
        Scalar::U16 | Scalar::F16 => (b as u16).to_string(),
        Scalar::U32 => (b as u32).to_string(),
        Scalar::U64 => b.to_string(),
    }
}

fn emit_struct(out: &mut String, def: &StructDef, plan: &Plan, ty: &dyn Fn(&Ty) -> String) {
    let name = rust_name(&def.name);
    let taken: Vec<&str> = def.fields.iter().map(|f| f.name.as_str()).collect();
    let mut pad = 0;
    let mut members = Vec::new();
    for slot in &plan.slots {
        match *slot {
            Slot::Field(i) => {
                let f = &def.fields[i];
                members.push((field_ident(&f.name), ty(&f.ty)));
            }
            Slot::Pad(n) => {
                let pad_name = loop {
                    let candidate = format!("_pad{pad}");
                    pad += 1;
                    if !taken.contains(&candidate.as_str()) {
                        break candidate;
                    }
                };
                members.push((pad_name, format!("[u8; {n}]")));
            }
        }
    }
    let _ = writeln!(
        out,
        "#[repr(C)]\n#[derive(Clone, Copy, Debug)]\npub struct {name} {{"
    );
    for (field, t) in &members {
        let _ = writeln!(out, "    pub {field}: {t},");
    }
    let _ = writeln!(
        out,
        "}}\n// SAFETY: every field is Pod (extern types are checked) and the asserts below rule out padding.\nunsafe impl ::orr_shaders::bytemuck::Zeroable for {name} {{}}\n// SAFETY: as above.\nunsafe impl ::orr_shaders::bytemuck::Pod for {name} {{}}\nconst _: () = {{"
    );
    let sum: Vec<String> = members
        .iter()
        .map(|(_, t)| format!("::core::mem::size_of::<{t}>()"))
        .collect();
    let _ = writeln!(
        out,
        "    assert!(::core::mem::size_of::<{name}>() == {});",
        if sum.is_empty() {
            "0".to_owned()
        } else {
            sum.join(" + ")
        }
    );
    emit_asserts(out, &name, def, plan);
    out.push_str("};\n");
}

fn emit_asserts(out: &mut String, path: &str, def: &StructDef, plan: &Plan) {
    let _ = writeln!(
        out,
        "    assert!(::core::mem::size_of::<{path}>() == {});",
        plan.size
    );
    for f in &def.fields {
        let _ = writeln!(
            out,
            "    assert!(::core::mem::offset_of!({path}, {}) == {});",
            field_ident(&f.name),
            f.offset
        );
    }
}

/// The Rust type for `ty` seen from a module `depth` levels below the include point.
pub(crate) fn rust_type(
    ty: &Ty,
    depth: usize,
    kernel: Option<&str>,
    owners: &HashMap<String, Owner>,
) -> String {
    let up = "super::".repeat(depth);
    match ty {
        Ty::Scalar(s) => s.rust().to_owned(),
        Ty::Vector(s, n) => format!("[{}; {n}]", s.rust()),
        Ty::Matrix {
            scalar, rows, cols, ..
        } => format!("[[{}; {cols}]; {rows}]", scalar.rust()),
        Ty::Array { element, len, .. } => {
            format!("[{}; {len}]", rust_type(element, depth, kernel, owners))
        }
        Ty::Pointer(p) => format!(
            "::orr_shaders::abi::GpuPtr<{}>",
            rust_type(p, depth, kernel, owners)
        ),
        Ty::Handle(h) => h.rust().to_owned(),
        Ty::Struct(name) => match owners.get(name) {
            Some(Owner::Extern(path)) => path.clone(),
            Some(Owner::Kernel) if kernel.is_some() => rust_name(name),
            _ => format!("{up}types::{}", rust_name(name)),
        },
    }
}

/// A Rust type name for a Slang struct name: generic arguments join with `_`.
pub(crate) fn rust_name(slang: &str) -> String {
    let mut s: String = slang
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect();
    while s.contains("__") {
        s = s.replace("__", "_");
    }
    s.trim_end_matches('_').to_owned()
}

const KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return",
    "self", "Self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where",
    "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final", "macro",
    "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen",
];

fn field_ident(name: &str) -> String {
    if KEYWORDS.contains(&name) {
        format!("r#{name}")
    } else {
        name.to_owned()
    }
}

/// A module identifier for a kernel path component.
pub(crate) fn ident(part: &str) -> String {
    let s: String = part
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '_'
            }
        })
        .collect();
    let s = if s.starts_with(|c: char| c.is_ascii_digit()) {
        format!("_{s}")
    } else {
        s
    };
    field_ident(&s)
}

/// `ALPHA_TEST` and `alphaTest` become `alpha_test`.
fn snake(name: &str) -> String {
    if name.chars().all(|c| !c.is_ascii_lowercase()) {
        return name.to_ascii_lowercase();
    }
    let mut out = String::new();
    for (i, c) in name.chars().enumerate() {
        if c.is_ascii_uppercase() {
            if i > 0 && !out.ends_with('_') {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}
